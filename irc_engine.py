def write_outputs(result: dict[str, Any]) -> tuple[str, str]:
    json_path = os.path.join(OUTDIR, "irc_result.json")
    txt_path = os.path.join(OUTDIR, "irc_result.txt")
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2, sort_keys=True)
        f.write("\n")
    lines = [
        f"IRC engine {SESSION_ID}  {SESSION_TS}",
        f"Class: {result['class_name']}",
        f"SHA-256: {result['sha256']}",
        f"Novelty capped: {result['novelty']['novelty_capped']}  Coherence: {result['novelty']['coherence']}",
        "",
        result["class_one_liner"],
        "",
        "LIVE RANKING",
    ]
    for i, r in enumerate(result["live_ranking"], 1):
        lines.append(
            f"  {i:02d}. {r['score']:7.2f}  {r['realm']:8s}  {r['id']:28s}  fold={r['fold']}  {r['label']}"
        )
    lines += ["", "ZEROED"]
    for z in result["zeroed"]:
        lines.append(f"  00. {z['id']:28s}  {z['realm']:8s}  {', '.join(z['reasons'])}")
    lines += ["", "PRIMARY"]
    p = result["primary"]
    if p:
        lines += [
            f"  {p['id']}  score={p['score']}  fold={p['fold']}",
            f"  LOW : {p['low_world']}",
            f"  HIGH: {p['high_world']}",
            f"  SRC : {p['source']}",
        ]
    lines += ["", "ADVERSARIAL"]
    for a in result["adversarial"]:
        lines.append(f"  TEMPT: {a['temptation']}")
        lines.append(f"  RULE : {a['ruling']}")
        lines.append("")
    with open(txt_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return json_path, txt_path


