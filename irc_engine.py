@dataclass
class IrcCase:
    id: str
    realm: str
    label: str
    point_estimate: str
    range_low: float
    range_high: float
    unit: str
    low_world: str
    high_world: str
    qualitative_reversal: bool
    sentence_omits_interval: bool
    load_bearing_sentence: str
    source: str
    status: str  # KNOWN | GAP | UNPROVED | SYNTHESIS | RETAIN | CONTROL
    evidence: float  # 0-1 sourcedness of the RANGE itself
    spoken: float  # 0-1 public/famous-mystery penalty
    prior_overlap: float  # 0-1 overlap with a named prior class
    reclaim: bool
    published_factor: float = 0.0  # Bar-On-style factor; 0 => use high/low envelope ratio
    notes: str = ""
    tags: list[str] = field(default_factory=list)

    def fold(self) -> float:
        """Scoring fold = published multiplicative factor when given.

        Bar-On reports a factor f around a point estimate (range ≈ point/f to
        point*f). Scoring on high/low would square that factor and let archaea
        beat bacteria by arithmetic, not by load. Envelope-only cases (mesopelagic
        1–33, soil 44–74) set published_factor to the envelope ratio itself.
        """
        if self.published_factor and self.published_factor > 1.0:
            return self.published_factor
        if self.range_low <= 0:
            return float("inf")
        return self.range_high / self.range_low

    def log_fold(self) -> float:
        f = self.fold()
        if not math.isfinite(f) or f <= 1:
            return 0.0
        return math.log10(f)


def validate_case(c: IrcCase) -> list[str]:
    errors = []
    if c.range_high < c.range_low:
        errors.append(f"{c.id}: range_high < range_low")
    if c.range_low <= 0 and c.range_high <= 0 and c.id not in RETAIN_ZERO:
        # signed quantities (e.g. w) only allowed on retain/control rows
        pass
    if not (0.0 <= c.evidence <= 1.0):
        errors.append(f"{c.id}: evidence out of [0,1]")
    if not (0.0 <= c.spoken <= 1.0):
        errors.append(f"{c.id}: spoken out of [0,1]")
    if not (0.0 <= c.prior_overlap <= 1.0):
        errors.append(f"{c.id}: prior_overlap out of [0,1]")
    if c.status not in {
        "KNOWN",
        "GAP",
        "UNPROVED",
        "SYNTHESIS",
        "RETAIN",
        "CONTROL",
    }:
        errors.append(f"{c.id}: bad status {c.status}")
    if c.qualitative_reversal and c.low_world.strip() == c.high_world.strip():
        errors.append(f"{c.id}: reversal=True but worlds identical")
    if (not c.qualitative_reversal) and c.low_world.strip() != c.high_world.strip():
        # allowed: worlds may be phrased differently without a true flip
        pass
    return errors


def irc_score(c: IrcCase) -> dict[str, Any]:
    """Heuristic score. Not a measurement of nature.

    irc = reversal * omit * log10(fold) * 40 * evidence * (1-spoken) * (1-overlap)
    Zeroed if reclaim, CONTROL/RETAIN, or listed in RETAIN_ZERO.
    """
    reasons_zero: list[str] = []
    if c.reclaim or c.id in RETAIN_ZERO or c.status in {"RETAIN", "CONTROL"}:
        reasons_zero.append("reclaim/control/retain")
    if not c.qualitative_reversal:
        reasons_zero.append("no qualitative reversal")
    if not c.sentence_omits_interval:
        reasons_zero.append("source already leads with interval")

    fold = c.fold()
    logf = c.log_fold()
    if logf <= 0:
        reasons_zero.append("fold <= 1")

    if reasons_zero:
        score = 0.0
    else:
        score = (
            1.0
            * (1.0 if c.sentence_omits_interval else 0.0)
            * logf
            * 40.0
            * max(c.evidence, 0.0)
            * (1.0 - c.spoken)
            * (1.0 - c.prior_overlap)
        )
        # preprint / UNPROVED haircut — interval structure can still apply
        if c.status == "UNPROVED":
            score *= 0.55
        if c.status == "SYNTHESIS":
            score *= 0.7

    return {
        "id": c.id,
        "realm": c.realm,
        "label": c.label,
        "score": round(score, 4),
        "fold": None if not math.isfinite(fold) else round(fold, 3),
        "log10_fold": round(logf, 4),
        "low_world": c.low_world,
        "high_world": c.high_world,
        "status": c.status,
        "zeroed": score == 0.0,
        "zero_reasons": reasons_zero,
        "evidence": c.evidence,
        "spoken": c.spoken,
        "prior_overlap": c.prior_overlap,
        "source": c.source,
        "load_bearing_sentence": c.load_bearing_sentence,
        "point_estimate": c.point_estimate,
        "unit": c.unit,
        "range": [c.range_low, c.range_high],
    }


