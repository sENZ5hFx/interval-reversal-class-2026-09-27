def novelty_cap(live_count: int, top_overlap: float) -> dict[str, Any]:
    """Novelty is structural and must be capped by prior-art adjacency."""
    # Adjacent to OAC, CIC two-clock, EFC, IPC. Not empty space.
    base = 0.44
    if top_overlap > 0.5:
        base -= 0.06
    if live_count < 2:
        base -= 0.08
    cap = max(0.28, min(0.46, base))
    return {
        "novelty_capped": round(cap, 2),
        "coherence": 0.83,
        "reason": (
            "Operator is distinct (one quantity, two qualitative worlds, omitted "
            "interval) but adjacent to OAC / CIC two-clock / EFC. Capped because "
            "the engine did not invent a new physical mechanism."
        ),
    }


def run() -> dict[str, Any]:
    catalog = build_catalog()
    errors: list[str] = []
    for c in catalog:
        errors.extend(validate_case(c))
    if errors:
        raise ValueError("catalog invalid: " + "; ".join(errors))

    ranked = sorted((irc_score(c) for c in catalog), key=lambda r: (-r["score"], r["id"]))
    live = [r for r in ranked if not r["zeroed"]]
    zeroed = [r for r in ranked if r["zeroed"]]
    primary = live[0] if live else None
    runner = live[1] if len(live) > 1 else None

    # Guard: bacteria must not lead
    if primary and primary["id"] == "bacteria_biomass":
        raise AssertionError("adversarial guard: bacteria 10× must not be primary (Dark Biosphere overlap)")

    # Guard: at least one control is zero
    assert any(r["id"] == "plants_gt_c" and r["zeroed"] for r in ranked)
    assert any(r["id"] == "hubble_tension" and r["zeroed"] for r in ranked)
    assert any(r["id"] == "sweetman_nodule_o2" and r["zeroed"] for r in ranked)

    cap = novelty_cap(len(live), primary["prior_overlap"] if primary else 1.0)

